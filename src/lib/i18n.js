export function translateCampaignCategory(locale, category) {
  const normalized = String(category || "")
    .trim()
    .toLowerCase();
  const entry = CAMPAIGN_CATEGORY_TRANSLATIONS[normalized];
  if (!entry) return category;
  return entry[locale] || entry.en;
}

export function translateFatwaCategory(locale, category) {
  const entry = FATWA_CATEGORY_TRANSLATIONS[category];
  if (!entry) return category;
  return entry[locale] || entry.en;
}

export function localizeSiteSettings(settings = {}, locale = "en") {
  const normalizedSettings = normalizeHeroDefaults(settings);

  if (locale === "bn") {
    return {
      ...normalizedSettings,
      ...BENGALI_SITE_SETTINGS,
      ...Object.fromEntries(
        Object.keys(BENGALI_SITE_SETTINGS)
          .map((key) => [key, normalizedSettings[`${key}_bn`]])
          .filter(([, value]) => typeof value === "string" && value.trim())
          .map(([key, value]) => [key.replace(/_bn$/, ""), value]),
      ),
    };
  }

  if (locale !== "ar") {
    return normalizedSettings;
  }

  const localized = {
    ...normalizedSettings,
    ...ARABIC_SITE_SETTINGS,
  };

  Object.keys(ARABIC_SITE_SETTINGS).forEach((key) => {
    const localizedOverride = normalizedSettings[`${key}_ar`];
    if (typeof localizedOverride === "string" && localizedOverride.trim()) {
      localized[key] = localizedOverride;
    }
  });

  return localized;
}

function normalizeHeroDefaults(settings = {}) {
  const next = { ...settings };

  if (
    !next.hero_subtitle ||
    next.hero_subtitle === "Dawah, Guidance, and Giving"
  ) {
    next.hero_subtitle = "IRWAA: Knowledge, Guidance, and Community";
  }

  if (
    !next.hero_title ||
    next.hero_title === "Knowledge That Guides, Causes That Matter"
  ) {
    next.hero_title = "Come Back to Allah With Knowledge, Mercy, and Action";
  }

  if (
    !next.hero_description ||
    next.hero_description ===
      "Build a stronger Muslim community through beneficial articles, trusted fatwas, and causes that turn faith into action."
  ) {
    next.hero_description =
      "For every heart searching for clarity, IRWAA brings Quran learning, trusted answers, and meaningful causes together so faith can become light in our homes and action in our communities.";
  }

  if (
    !next.hero_support_cta_text ||
    next.hero_support_cta_text === "Support our causes"
  ) {
    next.hero_support_cta_text = "Learn Quran";
  }

  return next;
}
