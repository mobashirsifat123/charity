create policy "scholar_profiles_select_own_or_admin"
on public.scholar_profiles
for select
using (
  public.is_admin()
  or user_id in (
    select id from public.users where lower(email) = public.current_user_email()
  )
);

drop policy if exists "scholar_profiles_insert_own_or_admin" on public.scholar_profiles;
create policy "scholar_profiles_insert_own_or_admin"
on public.scholar_profiles
for insert
with check (
  public.is_admin()
  or (
    public.is_scholar()
    and user_id in (
      select id from public.users where lower(email) = public.current_user_email()
    )
  )
);

drop policy if exists "scholar_profiles_update_own_or_admin" on public.scholar_profiles;
create policy "scholar_profiles_update_own_or_admin"
on public.scholar_profiles
