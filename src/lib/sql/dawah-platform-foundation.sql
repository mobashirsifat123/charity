  public.is_admin()
  or (
    public.is_scholar()
    and user_id in (
      select id from public.users where lower(email) = public.current_user_email()
    )
  )
)
with check (
  public.is_admin()
  or (
    public.is_scholar()
    and user_id in (
      select id from public.users where lower(email) = public.current_user_email()
    )
  )
